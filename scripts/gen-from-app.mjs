#!/usr/bin/env node
/**
 * Regenerates the pieces of this site that must stay identical to the app.
 *
 *   node scripts/gen-from-app.mjs [path/to/Gloumi/gloumi-app/src]
 *
 * Defaults to a sibling checkout of the app repository. Copied by machine
 * because each of these has drifted somewhere once it was copied by hand:
 * the wordmark outlines, the app icon, and the legal texts App Store Connect
 * points at.
 *
 * Writes:
 *   src/components/brand/Wordmark.tsx   <- theme/wordmarkPath.js
 *   public/brand/gloumi-mark.svg        <- the icon app.json declares as expo.icon
 *   src/content/legal-source.ts         <- constants/legal.js
 *   src/content/legal-translations.ts   <- constants/legalTranslations/<lang>.js
 */
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));

const SITE = path.resolve(__dirname, '..');
const APP = path.resolve(process.argv[2] || path.join(SITE, '..', 'Gloumi', 'gloumi-app', 'src'));

if (!fs.existsSync(path.join(APP, 'constants', 'legal.js'))) {
  console.error(`App source not found at ${APP}. Pass the path to gloumi-app/src as the first argument.`);
  process.exit(1);
}

/** legal.js and wordmarkPath.js are dependency-free ES modules: strip `export`, evaluate. */
function loadEsModule(file, names) {
  const src = fs.readFileSync(file, 'utf8').replace(/^export /gm, '');
  const sandbox = {};
  vm.runInNewContext(`${src}\n; __out = { ${names.join(', ')} };`, sandbox);
  return sandbox.__out;
}

function write(rel, content) {
  const abs = path.join(SITE, rel);
  fs.mkdirSync(path.dirname(abs), { recursive: true });
  fs.writeFileSync(abs, content);
  console.log('wrote', rel);
}

const json = (value) => JSON.stringify(value, null, 2);

// --- Wordmark ---------------------------------------------------------------
const wm = loadEsModule(path.join(APP, 'theme', 'wordmarkPath.js'), ['WORDMARK_ASPECT', 'WORDMARK_VIEWBOX', 'WORDMARK_PATHS']);

write(
  'src/components/brand/Wordmark.tsx',
  `import type { SVGProps } from "react";

/**
 * Gloumi wordmark as outlines – GENERATED by scripts/gen-from-app.mjs.
 *
 * Source: gloumi-app/src/theme/wordmarkPath.js, itself traced from
 * assets/Gloumi-text.svg. Outlines rather than live text so the letterforms do
 * not depend on Cormorant being loaded – the same reason the app ships no .ttf.
 */
export const WORDMARK_ASPECT = ${wm.WORDMARK_ASPECT};

export const WORDMARK_VIEWBOX = ${JSON.stringify(wm.WORDMARK_VIEWBOX)};

export const WORDMARK_PATHS: readonly string[] = ${json(wm.WORDMARK_PATHS)};

type WordmarkProps = Omit<SVGProps<SVGSVGElement>, "viewBox" | "role"> & {
  /** Accessible name. Pass an empty string when a visible label already names it. */
  title?: string;
};

export function Wordmark({ title = "Gloumi", className, ...rest }: WordmarkProps) {
  const decorative = title === "";
  return (
    <svg
      viewBox={WORDMARK_VIEWBOX}
      role={decorative ? undefined : "img"}
      aria-hidden={decorative ? true : undefined}
      aria-label={decorative ? undefined : title}
      focusable="false"
      fill="currentColor"
      className={className}
      {...rest}
    >
      {WORDMARK_PATHS.map((d, i) => (
        <path key={i} d={d} />
      ))}
    </svg>
  );
}
`
);

// --- Brand mark (the app icon) ------------------------------------------------
/*
 * The icon is COPIED, not transcribed into a component. The repository then
 * holds exactly one copy of the artwork, and the favicons, the OpenGraph card
 * and the footer all read that one file. An inline React version would be a
 * second copy to keep in step, which is the drift this script exists to stop.
 *
 * WHICH file is the icon is read from app.json rather than hard-coded. The app
 * renamed its mark once already (Gloumi-icon-light-default -> Gloumi-icon-10b),
 * and a hard-coded name would have left the site on the old one without saying
 * anything.
 */
const APP_ROOT = path.join(APP, '..');
const appJson = JSON.parse(fs.readFileSync(path.join(APP_ROOT, 'app.json'), 'utf8'));
const iconRef = appJson?.expo?.icon;
if (!iconRef) {
  console.error('app.json has no expo.icon, so there is no way to tell which file is the app icon.');
  process.exit(1);
}

const iconSvg = path.resolve(APP_ROOT, iconRef).replace(/\.[^.]+$/, '.svg');
if (!fs.existsSync(iconSvg)) {
  console.error(`app.json points at ${iconRef}, but no .svg sits beside it (${iconSvg}).`);
  console.error('The site needs the vector: the same mark is drawn from a 16px favicon up to the 1200px OG card.');
  process.exit(1);
}

const markTarget = path.join(SITE, 'public', 'brand', 'gloumi-mark.svg');
/*
 * Line endings are normalised to LF before writing and before comparing. The
 * app's copy is CRLF on Windows while .gitattributes keeps this one LF, so a
 * raw byte comparison announced "the mark changed" on every single run. A
 * check that cries wolf is a check people stop reading.
 */
const incoming = Buffer.from(fs.readFileSync(iconSvg, 'utf8').replace(/\r\n/g, '\n'), 'utf8');
const markChanged = !fs.existsSync(markTarget) || !incoming.equals(fs.readFileSync(markTarget));
fs.mkdirSync(path.dirname(markTarget), { recursive: true });
fs.writeFileSync(markTarget, incoming);
console.log('copied', path.basename(iconSvg), '-> public/brand/gloumi-mark.svg');

// --- Legal texts ------------------------------------------------------------
const legal = loadEsModule(path.join(APP, 'constants', 'legal.js'), ['LEGAL_META', 'PARTNER_META', 'LEGAL_DOCS']);

write(
  'src/content/legal-source.ts',
  `/**
 * Terms of Service, Privacy Policy and the Terms for Masters and Salons –
 * GENERATED by scripts/gen-from-app.mjs.
 *
 * Source of truth: gloumi-app/src/constants/legal.js in the Gloumi app
 * repository (Terms and Privacy ${legal.LEGAL_META.version}, ${legal.LEGAL_META.lastUpdated}; Terms for Masters and
 * Salons ${legal.PARTNER_META.version}, ${legal.PARTNER_META.lastUpdated}). The app shows this same text in
 * its LegalModal and App Store Connect points at the public copy, so the two
 * must never drift: change legal.js, then regenerate this file.
 *
 * The English text is a translation of the Lithuanian original; in case of
 * conflict the Lithuanian version prevails (stated in the source).
 */
export type LegalSection = {
  /** Stable anchor the app links to (e.g. "ranking", #152); most sections have none. */
  id?: string;
  title: string;
  paragraphs?: string[];
  bullets?: string[];
};

export type LegalLang = "lt" | "en";

export const LEGAL_META = ${json({ version: legal.LEGAL_META.version, lastUpdated: legal.LEGAL_META.lastUpdated })} as const;

/** The Terms for Masters and Salons are versioned on their own; masters already working must accept by requiredFrom. */
export const PARTNER_META = ${json({
    version: legal.PARTNER_META.version,
    lastUpdated: legal.PARTNER_META.lastUpdated,
    requiredFrom: legal.PARTNER_META.requiredFrom,
  })} as const;

export const LEGAL_DOCS: Record<LegalLang, { terms: LegalSection[]; privacy: LegalSection[]; partner: LegalSection[] }> = ${json(legal.LEGAL_DOCS)};
`
);

// --- Legal translations (K-ES2) ----------------------------------------------
/*
 * Terms and Privacy in further languages, written by the legal role in
 * constants/legalTranslations/<lang>.js (TERMS_<K>, PRIVACY_<K>, CONTROLLER_<K>,
 * optional NOTICE_<K>, VERSION_<K>, TITLE_TERMS_<K>, TITLE_PRIVACY_<K>). Only the
 * per-language files are read: index.js imports them, and an import cannot run
 * in the sandbox.
 *
 * A translation of another version than legal.js is left out – the app then
 * shows English, and so does the site. One whose sections do not line up with
 * the Lithuanian text stops the run: publishing it would put a mistranslated
 * structure online under the current version number.
 */
const TRANSLATED = { de: 'Deutsch', es: 'Español', fr: 'Français', it: 'Italiano', lv: 'Latviešu', pl: 'Polski' };

function loadOptional(file, names) {
  const src = fs.readFileSync(file, 'utf8').replace(/^export /gm, '');
  const sandbox = {};
  const pick = names.map((n) => `${n}: typeof ${n} === 'undefined' ? undefined : ${n}`).join(', ');
  vm.runInNewContext(`${src}\n; __out = { ${pick} };`, sandbox);
  return sandbox.__out;
}

function sameShape(lt, tr) {
  if (!Array.isArray(tr) || tr.length !== lt.length) return `${Array.isArray(tr) ? tr.length : 'no'} sections, Lithuanian has ${lt.length}`;
  for (let i = 0; i < lt.length; i++) {
    const a = lt[i];
    const b = tr[i];
    if ((a.id ?? null) !== (b.id ?? null)) return `section ${i + 1}: id ${b.id ?? '-'}, Lithuanian ${a.id ?? '-'}`;
    if ((a.paragraphs?.length ?? 0) !== (b.paragraphs?.length ?? 0)) return `section ${i + 1}: paragraph count differs`;
    if ((a.bullets?.length ?? 0) !== (b.bullets?.length ?? 0)) return `section ${i + 1}: bullet count differs`;
    if (typeof b.title !== 'string' || !b.title.trim()) return `section ${i + 1}: no title`;
  }
  return null;
}

const translations = [];
for (const [lang, name] of Object.entries(TRANSLATED)) {
  const file = path.join(APP, 'constants', 'legalTranslations', `${lang}.js`);
  if (!fs.existsSync(file)) continue;
  const K = lang.toUpperCase();
  const m = loadOptional(file, ['TERMS', 'PRIVACY', 'CONTROLLER', 'NOTICE', 'VERSION', 'TITLE_TERMS', 'TITLE_PRIVACY'].map((n) => `${n}_${K}`));
  if (m[`VERSION_${K}`] !== legal.LEGAL_META.version) {
    console.warn(`skipped ${lang}: translates ${m[`VERSION_${K}`] ?? 'no stated version'}, legal.js is ${legal.LEGAL_META.version}`);
    continue;
  }
  const problems = [
    typeof m[`CONTROLLER_${K}`] === 'string' ? null : 'no CONTROLLER',
    sameShape(legal.LEGAL_DOCS.lt.terms, m[`TERMS_${K}`]) && `terms: ${sameShape(legal.LEGAL_DOCS.lt.terms, m[`TERMS_${K}`])}`,
    sameShape(legal.LEGAL_DOCS.lt.privacy, m[`PRIVACY_${K}`]) && `privacy: ${sameShape(legal.LEGAL_DOCS.lt.privacy, m[`PRIVACY_${K}`])}`,
  ].filter(Boolean);
  if (problems.length) {
    console.error(`legalTranslations/${lang}.js does not match legal.js: ${problems.join('; ')}`);
    process.exit(1);
  }
  translations.push({
    lang,
    name,
    version: m[`VERSION_${K}`],
    notice: m[`NOTICE_${K}`] ?? null,
    controller: m[`CONTROLLER_${K}`],
    titles: { terms: m[`TITLE_TERMS_${K}`] ?? null, privacy: m[`TITLE_PRIVACY_${K}`] ?? null },
    terms: m[`TERMS_${K}`],
    privacy: m[`PRIVACY_${K}`],
  });
}

write(
  'src/content/legal-translations.ts',
  `/**
 * Terms of Service and Privacy Policy in further languages – GENERATED by
 * scripts/gen-from-app.mjs from gloumi-app/src/constants/legalTranslations
 * (K-ES2). Only translations of the current version (${legal.LEGAL_META.version}) are here; the
 * Lithuanian text prevails. Served at /legal/<lang>/terms and /legal/<lang>/privacy.
 */
import type { LegalSection } from "./legal-source";

export type TranslatedLegal = {
  /** BCP 47 code, also the URL segment. */
  lang: string;
  /** The language's own name, for links. */
  name: string;
  version: string;
  /** "This is a translation; the Lithuanian text prevails", in that language. */
  notice: string | null;
  controller: string;
  /** Document titles in that language, when the translation states them. */
  titles: { terms: string | null; privacy: string | null };
  terms: LegalSection[];
  privacy: LegalSection[];
};

export const LEGAL_TRANSLATIONS: TranslatedLegal[] = ${json(translations)};
`
);
console.log(`legal translations: ${translations.map((t) => t.lang).join(', ') || 'none'}`);

if (markChanged) {
  console.log('\nThe mark changed. Run `npm run icons` so the favicons are rebuilt from it.');
}
